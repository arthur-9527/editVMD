"""能力1（文本 → 动作）的 i2v 提示词模板。

为什么需要它
------------
MiniMax-H3 的图生视频（i2v）只吃一句「让画面发生什么变化」的描述，
但**人物动作类**视频对运镜 / 走位极其敏感：一旦模型自行推拉摇移或让人物
走出画面，后面的动捕就废了。所以这里把技能里实测有效的约束句固化下来：

    * 首帧固定为 pose.png（站立全身照），**不指定尾帧**。
    * 追加「固定机位 / 全身入镜 / 纯色背景 / 自然速度」固定句。
    * 描述动作时用「从起始姿势做出 X → 保持约1秒 → 缓慢回到起始姿势」。

这段文本只影响 i2v 生成的视频，不改变 pose.png 本身。
"""

from __future__ import annotations

# ★ 动作类视频的固定约束句（放在 prompt 末尾，防止运镜 / 走位 / 风格化）
SHOT_CONSTRAINT = (
    "固定机位镜头完全静止，全身完整入镜（头顶到脚都在画面内），"
    "简洁纯色浅灰背景，无其他人物和杂物，自然人体比例，正常速度"
)

# ★ 对人物动作类是毒药的关键词（若用户输入里出现，提示里也降权，不主动加）
FORBIDDEN_HINTS = (
    "电影感", "慢动作", "特写", "浅景深", "推拉摇移", "旋转镜头",
    "航拍", "风格化", "动漫化", "镜头跟随",
)


def build_i2v_prompt(text: str) -> str:
    """把用户的一句动作描述拼成 i2v 的 prompt。

    要点：
      * 首帧是一张站立全身照（pose.png），描述里强调「从站姿出发做动作」；
      * 动作幅度写足（模型对「幅度小」会理解成几乎不动）；
      * 末尾追加固定约束句。
    """
    action = " ".join((text or "").split()).strip()
    if not action:
        action = "轻轻挥挥手"

    parts = [
        "一位年轻女性，真实实拍，穿着浅灰色贴身运动服，站在纯白背景前。",
        f"从起始站姿出发，做出以下动作：{action}。",
        "动作幅度清晰明显，整个过程保持双脚原地基本不动，"
        "头部看向镜头，表情自然。",
        SHOT_CONSTRAINT,
    ]
    return "".join(parts)


# ---------------------------------------------------------------- 能力3：视频再编辑
#
# ★ 为什么必须显式写「以参考视频为基准、只改 X」
#   ref2v 只要不强调这一点，模型就会把动作整体重做（等于重新生成，
#   既白花钱又丢掉原来的动作）。所以模板的结构是：
#     ① 声明以参考视频为基准；
#     ② 锁定「起始站姿 / 动作节奏 / 构图 / 背景」不动；
#     ③ 把用户改动**限定**进「只做以下调整：…」；
#     ④ 没给改动时退化成「原样复现一遍」。
#   末尾继续复用 SHOT_CONSTRAINT（固定机位 / 全身 / 纯色背景）——
#   这是动捕成败的关键，任何链路都不能省。


def build_refine_prompt(change: str) -> str:
    """把「对既有视频的改动要求」拼成 ref2v 的 prompt。"""
    tweak = " ".join((change or "").split()).strip()
    if not tweak:
        tweak = "原样保持，动作与节奏不要改变"

    parts = [
        "一位年轻女性，真实实拍，穿着浅灰色贴身运动服，站在纯白背景前。",
        "以参考视频中的动作为基准，保持原有的起始站姿、动作节奏、"
        "全身构图与纯色背景不变。",
        f"只做以下调整：{tweak}。",
        "除上述调整外，其余动作与参考视频保持一致。",
        "动作幅度清晰明显，整个过程保持双脚原地基本不动，"
        "头部看向镜头，表情自然。",
        SHOT_CONSTRAINT,
    ]
    return "".join(parts)
